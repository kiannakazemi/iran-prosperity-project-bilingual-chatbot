# ── Global engine (loaded once at startup) ───────────────────────────

_engine: ChatEngine | None = None

# Dedicated thread-pool for blocking I/O so we never starve the event loop.
_io_pool = ThreadPoolExecutor(max_workers=4, thread_name_prefix="rag-io")

# Safety ceiling for the retrieval step (seconds).
RETRIEVAL_TIMEOUT = 60


@asynccontextmanager
async def lifespan(app: FastAPI):
    global _engine
    print("Starting up — loading RAG pipeline …")
    init_db()
    _engine = ChatEngine()
    print("API ready.")
    yield
    _io_pool.shutdown(wait=False)
    print("Shutting down.")


app = FastAPI(
    title="Iran Prosperity Project — RAG Chatbot API",
    description=(
        "Bilingual (English/Persian) RAG chatbot for the IPP Emergency Phase Booklet. "
        "Dense retrieval (Cohere embed-multilingual-v3.0 + Qdrant) with Cohere "
        "rerank-v3.5, answers generated by Gemini Flash-Lite."
    ),
    version="1.0.0",
    lifespan=lifespan,
)

